// the rest is interpolated to join them and is marked as such per-record.
const realDam = {
  "2026-08-09": { m: 161.81, source: "mb-2026-08-10" },
  "2026-08-10": { m: 170.74, source: "mb-2026-08-10" },
};

const days = rainfall.map((rain_mm, i) => {
  const date = new Date(START + i * DAY).toISOString().slice(0, 10);
  const real = realDam[date];
  let angat_m;
  if (real) angat_m = real.m;
  else if (i < 4) angat_m = Math.round((157.5 + i * 1.1) * 100) / 100;
  else if (i === 4) angat_m = 161.81;
  else angat_m = Math.round((170.74 + Math.min(0, (i - 5) * -0.28) + rain_mm * 0.012) * 100) / 100;
  return {
    date,
    rain_mm,
    rain_dataClass: "schematic",
    tide_max_m: tideMax(i),
    tide_dataClass: "schematic",
    angat_reservoir_m: angat_m,
    angat_dataClass: real ? "reported" : "schematic",
    angat_source: real ? real.source : null,
  };
});

