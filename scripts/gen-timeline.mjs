const START = Date.UTC(2026, 7, 5); // 2026-08-05
const DAY = 86400000;

// Schematic Manila Bay daily higher-high water, metres above mean sea level.
// A semi-diurnal spring-neap envelope, NOT an official tide prediction.
// Replace with NAMRIA / PAGASA tide tables (sources.json -> namria-tides).
function tideMax(i) {
  const springNeap = Math.cos((2 * Math.PI * (i - 3)) / 14.77);
  const amp = 0.74 + 0.22 * springNeap;
  const seasonal = 0.06; // northeast-monsoon-season bay set-up allowance
  return Math.round((amp + seasonal) * 100) / 100;
}

